import assert from 'node:assert/strict';
import {writeFile} from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
import {resolve} from 'node:path';
import {load} from './load.js';
const env=await load();
const {PluginCatalog}=await import(pathToFileURL(resolve(env.paths.rix,'src/runtime/plugin-catalog.js')));
const {createOperatorMetadataCache}=env.cache;
const source='##OPS##\n:<plus>: Plus :infix :additive :left\n##OPS##\n1;';
const options={label:'alpha.rix',owner:{pluginId:'alpha',mount:'alpha'}};
let checks=0;
function check(fn){fn();checks++;}
const c=createOperatorMetadataCache({maxEntries:2,maxBytes:4096});
const first=c.get(source,options);
check(()=>assert.ok(Object.isFrozen(first[0])&&Object.isFrozen(first[0].target)));
first[0]={target:{method:'CORRUPTED'}};
check(()=>assert.equal(c.get(source,options)[0].target.method,'PLUS'));
check(()=>assert.equal(c.stats().hits,1));
const second=c.get(source,{...options,owner:{pluginId:'beta',mount:'beta'}});
check(()=>assert.equal(second[0].target.pluginId,'beta'));
const third=c.get(source,{...options,owner:{pluginId:'alpha',mount:'other'}});
check(()=>assert.equal(third[0].target.mount,'other'));
check(()=>assert.equal(c.stats().evictions,1));
c.get(source+'\n2;',options);check(()=>assert.equal(c.stats().misses,4));
c.get(source,{...options,label:'another.rix'});check(()=>assert.equal(c.stats().misses,5));
const broken='##OPS##\n:<oops>: nope\n##OPS##';
for(const label of ['first.rix','second.rix'])check(()=>assert.throws(()=>c.get(broken,{...options,label}),new RegExp(label.replace('.','\\.'))));
check(()=>assert.equal(c.stats().errors,2));
const tiny=createOperatorMetadataCache({maxEntries:2,maxBytes:1});tiny.get(source,options);tiny.get(source,options);
check(()=>assert.equal(tiny.stats().entries,0));check(()=>assert.equal(tiny.stats().parses,2));
const bounded=createOperatorMetadataCache({maxEntries:3,maxBytes:600});
for(let i=0;i<20;i++)bounded.get(`\n${i};`,{...options,label:`file-${i}`});
check(()=>assert.ok(bounded.stats().entries<=3&&bounded.stats().estimatedBytes<=600));
const metadata={id:'alpha',description:'Test',kind:'rix',mount:'alpha'};
const add=(m=metadata,src=source,path='alpha.rix')=>new PluginCatalog().addMetadata(m,{kind:'rix',source:src,sourcePath:path});
env.cache.clearOperatorMetadataCache();
const a=add();a.operatorDefinitions[0]={target:{method:'MUTATED'}};const b=add();
check(()=>assert.ok(Object.isFrozen(b.operatorDefinitions[0].target)));
check(()=>assert.equal(b.operatorDefinitions[0].target.method,'PLUS'));
check(()=>assert.notEqual(a.operatorDefinitions,b.operatorDefinitions));
check(()=>assert.equal(env.cache.operatorMetadataCacheStats().hits,1));
const own=[];const explicit=add({...metadata,operatorDefinitions:own});
check(()=>assert.equal(explicit.operatorDefinitions,own));
const duplicate=new PluginCatalog();duplicate.addMetadata(metadata,{source,sourcePath:'alpha.rix'});
check(()=>assert.throws(()=>duplicate.addMetadata(metadata,{source,sourcePath:'alpha.rix'}),/Duplicate/));
const collision=new PluginCatalog();collision.addMetadata(metadata,{source,sourcePath:'alpha.rix'});
check(()=>assert.throws(()=>collision.addMetadata({...metadata,id:'beta'},{source,sourcePath:'beta.rix'}),/conflicts/));
check(()=>assert.throws(()=>add({...metadata,id:''}),/non-empty id/));
const one=env.makeSession(),two=env.makeSession();
check(()=>assert.notEqual(one.systemContext._pluginCatalog,two.systemContext._pluginCatalog));
env.run('.Plugin.Load("poly"); P := .poly([1,2,3]); P(2);',one);
check(()=>assert.equal(one.systemContext._pluginCatalog.loaded.has('poly'),true));
check(()=>assert.equal(two.systemContext._pluginCatalog.loaded.has('poly'),false));
check(()=>assert.equal(env.run('2+3;',two).toString(),'5'));
const host=new PluginCatalog();host.addMetadata({id:'poly',description:'Host replacement',kind:'host',mount:'customPoly'},{kind:'host'});
const system=env.rix.createDefaultSystemContext({pluginCatalog:host});
check(()=>assert.equal(system._pluginCatalog.info('poly').mount,'customPoly'));
const report={timestamp:new Date().toISOString(),runtime:process.versions,checks,cache:env.cache.operatorMetadataCacheStats(),passed:true};
await writeFile(new URL(`results/verification-${process.versions.bun?'bun':'node'}.json`,import.meta.url),JSON.stringify(report,null,2)+'\n');console.log(JSON.stringify({checks,passed:true,cache:report.cache}));
