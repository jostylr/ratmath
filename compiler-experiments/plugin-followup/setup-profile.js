import { Session } from 'node:inspector';
import { resolve,dirname } from 'node:path';
import { fileURLToPath,pathToFileURL } from 'node:url';
import { writeFile,mkdir } from 'node:fs/promises';
const here=dirname(fileURLToPath(import.meta.url));
const root=process.env.RATMATH_ROOT||resolve(here,'../..');
const {createDefaultSystemContext}=await import(pathToFileURL(resolve(root,'rix/src/index-node.js')));
createDefaultSystemContext();
const inspector=new Session();inspector.connect();
const post=(name,args={})=>new Promise((resolve,reject)=>inspector.post(name,args,(error,value)=>error?reject(error):resolve(value)));
await post('Profiler.enable');await post('Profiler.start');
for(let i=0;i<8;i++)createDefaultSystemContext();
const {profile}=await post('Profiler.stop');inspector.disconnect();
const nodes=new Map(profile.nodes.map(n=>[n.id,n]));const counts=new Map();
for(const id of profile.samples||[])counts.set(id,(counts.get(id)||0)+1);
const total=profile.samples.length;
const top=[...counts].sort((a,b)=>b[1]-a[1]).slice(0,20).map(([id,n])=>({function:nodes.get(id).callFrame.functionName,url:nodes.get(id).callFrame.url.replace(root,'<root>'),percent:100*n/total}));
await mkdir(resolve(here,'results'),{recursive:true});
await writeFile(resolve(here,'results/setup-profile-node.json'),JSON.stringify({timestamp:new Date().toISOString(),runtime:process.version,totalSamples:total,top},null,2)+'\n');console.log(JSON.stringify(top.slice(0,10),null,2));
